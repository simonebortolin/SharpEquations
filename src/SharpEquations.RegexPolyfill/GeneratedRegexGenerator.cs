namespace SharpEquations.RegexPolyfill
{
    using System.Collections.Generic;
    using System.Linq;
    using System.Text;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.CSharp;
    using Microsoft.CodeAnalysis.CSharp.Syntax;

    /// <summary>
    /// [GeneratedRegex] where .NET has no regular expression generator (.NET Standard 2.0, .NET Framework): the
    /// attribute, and for each partial method that carries it a <c>Regex</c> built once from its pattern, options and
    /// timeout. The culture name, which the Regex constructors do not take, is not used.
    /// </summary>
    [Generator]
    public sealed class GeneratedRegexGenerator : IIncrementalGenerator
    {
        private const string AttributeName = "System.Text.RegularExpressions.GeneratedRegexAttribute";

        private const string Regex = "global::System.Text.RegularExpressions.Regex";

        private const string AttributeSource = @"// <auto-generated/>
namespace System.Text.RegularExpressions
{
    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
    internal sealed class GeneratedRegexAttribute : global::System.Attribute
    {
        public GeneratedRegexAttribute(string pattern) : this(pattern, RegexOptions.None) { }

        public GeneratedRegexAttribute(string pattern, RegexOptions options) : this(pattern, options, -1) { }

        public GeneratedRegexAttribute(string pattern, RegexOptions options, string cultureName) : this(pattern, options, -1, cultureName) { }

        public GeneratedRegexAttribute(string pattern, RegexOptions options, int matchTimeoutMilliseconds) : this(pattern, options, matchTimeoutMilliseconds, """") { }

        public GeneratedRegexAttribute(string pattern, RegexOptions options, int matchTimeoutMilliseconds, string cultureName)
        {
            Pattern = pattern;
            Options = options;
            MatchTimeoutMilliseconds = matchTimeoutMilliseconds;
            CultureName = cultureName;
        }

        public string Pattern { get; }

        public RegexOptions Options { get; }

        public int MatchTimeoutMilliseconds { get; }

        public string CultureName { get; }
    }
}
";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(static c => c.AddSource("GeneratedRegexAttribute.g.cs", AttributeSource));
            var methods = context.SyntaxProvider.ForAttributeWithMetadataName(
                    AttributeName,
                    static (node, _) => node is MethodDeclarationSyntax,
                    static (c, _) => Generate(c))
                .Where(static m => m.HasValue)
                .Select(static (m, _) => m!.Value);
            context.RegisterSourceOutput(methods, static (c, m) => c.AddSource(m.HintName, m.Source));
        }

        /// <summary>The file of the method, or null if the attribute has no pattern (the compiler reports it).</summary>
        private static (string HintName, string Source)? Generate(GeneratorAttributeSyntaxContext context)
        {
            if (context.TargetSymbol is not IMethodSymbol method || context.Attributes.Length == 0)
                return null;
            var arguments = context.Attributes[0].ConstructorArguments;
            if (arguments.Length == 0 || arguments[0].Value is not string pattern)
                return null;
            var options = arguments.Length > 1 && arguments[1].Value is int o ? o : 0;
            var timeout = arguments.Length > 2 && arguments[2].Value is int t && t != -1 ? t : (int?)null;

            var types = new List<INamedTypeSymbol>();
            for (var type = method.ContainingType; type != null; type = type.ContainingType)
                types.Insert(0, type);
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            var ns = method.ContainingNamespace;
            if (!ns.IsGlobalNamespace)
                source.Append("namespace ").Append(ns.ToDisplayString()).Append("\n{\n");
            foreach (var type in types)
                source.Append("partial ").Append(Kind(type)).Append(' ').Append(type.Name).Append(TypeParameters(type)).Append("\n{\n");

            var field = "__" + method.Name + "Regex";
            source.Append("private static readonly ").Append(Regex).Append(' ').Append(field).Append(" = new ").Append(Regex).Append('(')
                .Append(SymbolDisplay.FormatLiteral(pattern, true))
                .Append(", (global::System.Text.RegularExpressions.RegexOptions)").Append(options);
            if (timeout.HasValue)
                source.Append(", global::System.TimeSpan.FromMilliseconds(").Append(timeout.Value).Append(')');
            source.Append(");\n");
            source.Append(SyntaxFacts.GetText(method.DeclaredAccessibility)).Append(method.IsStatic ? " static" : "")
                .Append(" partial ").Append(Regex).Append(' ').Append(method.Name).Append("() => ").Append(field).Append(";\n");

            source.Append('}', types.Count + (ns.IsGlobalNamespace ? 0 : 1));
            source.Append('\n');
            var name = string.Join(".", types.Select(type => type.MetadataName)) + "." + method.Name;
            var hintName = (ns.IsGlobalNamespace ? "" : ns.ToDisplayString() + ".") + name.Replace('`', '_') + ".g.cs";
            return (hintName, source.ToString());
        }

        private static string Kind(INamedTypeSymbol type) =>
            type.IsRecord ? type.IsValueType ? "record struct" : "record" :
            type.TypeKind switch
            {
                TypeKind.Struct => "struct",
                TypeKind.Interface => "interface",
                _ => "class",
            };

        private static string TypeParameters(INamedTypeSymbol type) =>
            type.TypeParameters.Length == 0 ? "" : "<" + string.Join(", ", type.TypeParameters.Select(p => p.Name)) + ">";
    }
}
